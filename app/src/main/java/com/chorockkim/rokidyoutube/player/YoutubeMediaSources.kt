package com.chorockkim.rokidyoutube.player

import android.content.Context
import android.net.Uri
import android.util.Log
import com.chorockkim.rokidyoutube.net.OkHttpDownloader
import com.google.android.exoplayer2.MediaItem
import com.google.android.exoplayer2.source.MediaSource
import com.google.android.exoplayer2.source.MergingMediaSource
import com.google.android.exoplayer2.source.ProgressiveMediaSource
import com.google.android.exoplayer2.source.dash.DashMediaSource
import com.google.android.exoplayer2.source.dash.DefaultDashChunkSource
import com.google.android.exoplayer2.source.dash.manifest.DashManifest
import com.google.android.exoplayer2.source.dash.manifest.DashManifestParser
import com.google.android.exoplayer2.source.hls.HlsMediaSource
import com.google.android.exoplayer2.upstream.DataSource
import com.google.android.exoplayer2.upstream.DefaultDataSource
import com.google.android.exoplayer2.upstream.DefaultHttpDataSource
import java.io.ByteArrayInputStream
import org.schabi.newpipe.extractor.services.youtube.dashmanifestcreators.YoutubeOtfDashManifestCreator
import org.schabi.newpipe.extractor.services.youtube.dashmanifestcreators.YoutubePostLiveStreamDvrDashManifestCreator
import org.schabi.newpipe.extractor.services.youtube.dashmanifestcreators.YoutubeProgressiveDashManifestCreator
import org.schabi.newpipe.extractor.stream.AudioStream
import org.schabi.newpipe.extractor.stream.DeliveryMethod
import org.schabi.newpipe.extractor.stream.Stream
import org.schabi.newpipe.extractor.stream.StreamInfo
import org.schabi.newpipe.extractor.stream.StreamType
import org.schabi.newpipe.extractor.stream.VideoStream

/**
 * Turns a [StreamInfo] into an ExoPlayer [MediaSource]. Ported from RokidPipe/NewPipe's
 * PlaybackResolver + PlayerDataSource: YouTube adaptive streams are played through DASH
 * manifests generated by NewPipeExtractor and fetched with [YoutubeHttpDataSource], which is
 * what keeps YouTube from throttling or rejecting the requests.
 */
class YoutubeMediaSources(context: Context) {
    private val appContext = context.applicationContext

    private val genericFactory: DataSource.Factory = DefaultDataSource.Factory(
        appContext,
        DefaultHttpDataSource.Factory().setUserAgent(OkHttpDownloader.USER_AGENT)
    )
    private val ytHlsFactory = youtubeFactory(range = false, rn = false)
    private val ytDashFactory = youtubeFactory(range = true, rn = true)
    private val ytProgressiveFactory = youtubeFactory(range = false, rn = true)

    class ResolverException(message: String, cause: Throwable? = null) : Exception(message, cause)

    /** @return the media source for [selection], or throws [ResolverException]. */
    fun build(info: StreamInfo, selection: StreamSelector.Selection): MediaSource {
        if (info.streamType == StreamType.LIVE_STREAM || info.streamType == StreamType.AUDIO_LIVE_STREAM) {
            if (info.hlsUrl.isNotEmpty()) {
                return HlsMediaSource.Factory(genericFactory)
                    .setAllowChunklessPreparation(true)
                    .createMediaSource(MediaItem.fromUri(info.hlsUrl))
            }
            throw ResolverException("Live stream without an HLS URL is not supported")
        }

        val sources = listOfNotNull(selection.video, selection.audio).map { build(info, it) }
        return when (sources.size) {
            0 -> throw ResolverException("No playable stream")
            1 -> sources[0]
            else -> MergingMediaSource(true, *sources.toTypedArray())
        }
    }

    private fun build(info: StreamInfo, stream: Stream): MediaSource {
        if (stream.content.isNullOrEmpty()) throw ResolverException("Empty stream URL")
        val item = MediaItem.Builder()
            .setUri(Uri.parse(stream.content))
            .setCustomCacheKey("${info.id} ${stream.id} ${stream.format?.name}")
            .build()

        if (info.streamType == StreamType.POST_LIVE_STREAM) {
            return try {
                val itag = requireNotNull(stream.itagItem)
                val manifest = YoutubePostLiveStreamDvrDashManifestCreator
                    .fromPostLiveStreamDvrStreamingUrl(
                        stream.content, itag, itag.targetDurationSec, info.duration
                    )
                dash(manifest, stream, item)
            } catch (e: Exception) {
                throw ResolverException("Could not build DASH manifest of ended live stream", e)
            }
        }

        return when (stream.deliveryMethod) {
            DeliveryMethod.PROGRESSIVE_HTTP -> {
                val adaptive = (stream is VideoStream && stream.isVideoOnly()) || stream is AudioStream
                if (!adaptive) {
                    progressive(item)
                } else {
                    try {
                        val manifest = YoutubeProgressiveDashManifestCreator
                            .fromProgressiveStreamingUrl(
                                stream.content, requireNotNull(stream.itagItem), info.duration
                            )
                        dash(manifest, stream, item)
                    } catch (e: Exception) {
                        Log.w(TAG, "DASH manifest failed, falling back to progressive", e)
                        progressive(item)
                    }
                }
            }

            DeliveryMethod.DASH -> try {
                val manifest = YoutubeOtfDashManifestCreator.fromOtfStreamingUrl(
                    stream.content, requireNotNull(stream.itagItem), info.duration
                )
                dash(manifest, stream, item)
            } catch (e: Exception) {
                throw ResolverException("Could not build DASH manifest of OTF stream", e)
            }

            DeliveryMethod.HLS -> HlsMediaSource.Factory(ytHlsFactory).createMediaSource(item)

            else -> throw ResolverException("Unsupported delivery method ${stream.deliveryMethod}")
        }
    }

    private fun progressive(item: MediaItem): MediaSource =
        ProgressiveMediaSource.Factory(ytProgressiveFactory).createMediaSource(item)

    private fun dash(manifestText: String, stream: Stream, item: MediaItem): MediaSource {
        val manifest: DashManifest = DashManifestParser().parse(
            Uri.parse(stream.manifestUrl ?: ""),
            ByteArrayInputStream(manifestText.toByteArray(Charsets.UTF_8))
        )
        return DashMediaSource.Factory(DefaultDashChunkSource.Factory(ytDashFactory), ytDashFactory)
            .createMediaSource(manifest, item)
    }

    private fun youtubeFactory(range: Boolean, rn: Boolean): DataSource.Factory =
        DefaultDataSource.Factory(
            appContext,
            YoutubeHttpDataSource.Factory()
                .setRangeParameterEnabled(range)
                .setRnParameterEnabled(rn)
        )

    private companion object {
        const val TAG = "YoutubeMediaSources"
    }
}
